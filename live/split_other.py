def strip_tag(n):
    """去掉 [HD]/[BD]/[VGA]/[SD] 前缀和 (576p) 后缀"""
    n = re.sub(r'^\s*\[(?:HD|BD|VGA|SD|FHD|4K)\]\s*', '', n, flags=re.I)
    n = re.sub(r'\s*\((?:\d{3,4}p|FHD|HD|4K)\)\s*$', '', n, flags=re.I)
    n = re.sub(r'FHD$', '', n, flags=re.I)
    return n.strip()


def is_cctv(n):
    return bool(re.match(r'(?i)^(cctv|cgtn|gctn)', n.replace('-', '').replace(' ', ''))) or n.startswith('央视')


def prov_of(n):
    """判断频道属于哪个省：先找城市，再找省名+地面频道词"""
    for city in _CITY_KEYS:
        if n.startswith(city):
            return CITY_PROV[city]
    for p in PROVINCES:
        if n.startswith(p) and any(w in n for w in LOCAL_SUFFIX):
            return p
    for p in PROVINCES:
        if p in n and any(w in n for w in LOCAL_SUFFIX):
            return p
    return None


def classify(name):
    raw = name
    n = strip_tag(name)
    nn = n.replace(' ', '')
    if is_cctv(nn):
        return '央视'
    if '卫视' in n:
        return '卫视'
    if '4K' in n.upper() or '超高清' in n:
        return '4K超清'
    nl = n.lower()
    if any(w.lower() in nl for w in INTL_WORDS):
        return '国际'
    if any(w in n for w in DRAMA_WORDS):
        return '剧场轮播'
    if any(w in n for w in IPTV_WORDS):
        return 'IPTV专区'
    p = prov_of(n)
    if p:
        return f'地方·{p}'
    if any(w in nl for w in ['sport', '体育', '赛事', '足球', '篮球']):
        return '体育'
    if any(w in n for w in ['卡通', '少儿', '中学生']):
        return '少儿'
    return '其他'


def main():
    p = os.path.join(BASE, 'live_groups.json')
    groups = json.load(open(p))
    out = []
    prov_buckets = {}
    misc = {}

    for g in groups:
        if g['name'] != '其他':
            out.append(g)
            continue
        for ch in g['channel']:
            k = classify(ch['name'])
            if k.startswith('地方·'):
                prov_buckets.setdefault(k, []).append(ch)
            else:
                misc.setdefault(k, []).append(ch)

    # 央视/卫视的变体（[HD]cctv14、[VGA]河南卫视…）并回原有组，不能丢
    for g in out:
        nm = g['name']
        if nm in ('央视', '卫视') and misc.get(nm):
            have = {c['name'] for c in g['channel']}
            g['channel'].extend(c for c in misc[nm] if c['name'] not in have)
            misc.pop(nm)

    # 国际组同理并入
    for g in out:
        if g['name'] == '国际' and misc.get('国际'):
            have = {c['name'] for c in g['channel']}
            g['channel'].extend(c for c in misc['国际'] if c['name'] not in have)
            misc.pop('国际')

    # 频道数 <3 的省份并入「地方·其他」，避免分组过碎
    small = [k for k, v in prov_buckets.items() if len(v) < 3]
    if small:
        merged = []
        for k in small:
            merged += prov_buckets.pop(k)
        prov_buckets['地方·其他'] = merged

    # 固定顺序输出
    order = ['4K超清', '剧场轮播', 'IPTV专区', '体育', '少儿']
    for k in order:
        if misc.get(k):
            out.append({'name': k, 'channel': misc[k]})
    for k in sorted(prov_buckets, key=lambda x: (-len(prov_buckets[x]), x)):
        # 同城前缀排在一起：长沙…长沙…、郴州…郴州…
        out.append({'name': k, 'channel': sorted(prov_buckets[k], key=lambda c: c['name'])})
    if misc.get('其他'):
        out.append({'name': '其他', 'channel': misc['其他']})

    json.dump(out, open(p, 'w'), ensure_ascii=False, indent=1)
    print('分组结果:')
    for g in out:
        print(f"  {g['name']:<12} {len(g['channel']):>3}")
    print('合计', sum(len(g['channel']) for g in out))
    for k in ('其他', '4K超清', '剧场轮播', 'IPTV专区', '体育', '国际'):
        if misc.get(k):
            print(f"\n[{k}]", ', '.join(c['name'] for c in misc[k][:14]))


if __name__ == '__main__':
    main()
